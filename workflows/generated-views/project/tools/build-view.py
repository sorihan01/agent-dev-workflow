#!/usr/bin/env python3
"""Build a read-only view from the documents that own each fact.

A view is never a second home. Each row in views/<name>.json names a source
path that must exist and an extract rule that must find something; otherwise
the build fails. Nothing in the output is typed by hand: counts come from the
file system, text is copied from the source verbatim.

    python3 tools/build-view.py            # write views/<name>.md for every spec
    python3 tools/build-view.py --check    # exit 1 if a committed view is stale or a source broke
    python3 tools/build-view.py --quiet    # with --check: silent when everything is fresh

Extract rules:
    count:<glob>        number of files matching <glob> inside the source folder
    line:<regex>        first line in the source file matching <regex> (group 1 if given)
    section:<heading>   the lines under "## <heading>" up to the next heading
"""
import fnmatch
import glob
import json
import os
import re
import sys

ROOT = os.environ.get("CLAUDE_PROJECT_DIR") or os.getcwd()
VIEWS = os.path.join(ROOT, "views")
check, quiet = "--check" in sys.argv, "--quiet" in sys.argv


class SourceError(Exception):
    pass


def extract(source, rule):
    path = os.path.join(ROOT, source)
    if not os.path.exists(path):
        raise SourceError(f"source not found: {source}")
    kind, _, arg = rule.partition(":")
    if kind == "count":
        if not os.path.isdir(path):
            raise SourceError(f"count needs a folder: {source}")
        return str(len([f for f in os.listdir(path) if fnmatch.fnmatch(f, arg)]))
    if os.path.isdir(path):
        raise SourceError(f"{kind} needs a file: {source}")
    lines = open(path, encoding="utf-8").read().splitlines()
    if kind == "line":
        for line in lines:
            m = re.search(arg, line)
            if m:
                return (m.group(1) if m.groups() else line).strip()
        raise SourceError(f"no line matches /{arg}/ in {source}")
    if kind == "section":
        out, inside = [], False
        for line in lines:
            if re.match(r"^#{1,6} ", line):
                if inside:
                    break
                inside = line.lstrip("#").strip().lower() == arg.lower()
                continue
            if inside and line.strip():
                out.append(line.strip())
        if not out:
            raise SourceError(f"section '{arg}' missing or empty in {source}")
        return "<br>".join(out)
    raise SourceError(f"unknown extract rule '{rule}' (use count:, line:, section:)")


def render(name, spec):
    rows = [f"# {spec.get('title', name)}", "",
            f"> Generated by `tools/build-view.py` from `views/{name}.json`. Don't edit by hand: "
            "change the source document, then run `python3 tools/build-view.py`.", "",
            "| Fact | Value | Source |", "|---|---|---|"]
    for item in spec["facts"]:
        value = extract(item["source"], item["extract"]).replace("|", "\\|")
        rows.append(f"| {item['label']} | {value} | [`{item['source']}`]({os.path.relpath(os.path.join(ROOT, item['source']), VIEWS)}) |")
    return "\n".join(rows) + "\n"


specs = sorted(glob.glob(os.path.join(VIEWS, "*.json")))
if not specs and not quiet:
    print("build-view: no views/*.json specs yet")
problems, written = [], []
for spec_path in specs:
    name = os.path.splitext(os.path.basename(spec_path))[0]
    out_path = os.path.join(VIEWS, f"{name}.md")
    try:
        text = render(name, json.load(open(spec_path, encoding="utf-8")))
    except (SourceError, KeyError, json.JSONDecodeError) as e:
        problems.append(f"views/{name}.json: {e}")
        continue
    current = open(out_path, encoding="utf-8").read() if os.path.exists(out_path) else None
    if check:
        if current != text:
            problems.append(f"views/{name}.md is stale: a source changed since it was built")
    elif current != text:
        open(out_path, "w", encoding="utf-8").write(text)
        written.append(f"views/{name}.md")

if problems:
    print("build-view: " + ("; ".join(problems)) + " → fix the source, then run `python3 tools/build-view.py`")
    sys.exit(1)
if not quiet:
    print("build-view: " + (f"wrote {', '.join(written)}" if written else f"{len(specs)} view(s) up to date"))
